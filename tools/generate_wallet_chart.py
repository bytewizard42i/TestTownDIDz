#!/usr/bin/env python3
"""Write docs/PREPROD_WALLETS.md: a readable chart of every public address.

WHAT THIS IS
    A human-readable preview of the machine-readable truth in
    tools/wallet-assignments.json plus the named operator wallets in
    tools/generate_population.py. Everything in it is a PUBLIC half:
    addresses are safe to publish. Seeds never appear here or anywhere in
    the repo (docs/SECRETS_CONVENTION.md).

WHY GENERATED
    If a wallet is ever re-keyed, the chart would quietly go stale. Run
        python3 tools/generate_wallet_chart.py
    after changing assignments. tests/test_wallets_and_exchange.py fails if
    the committed chart no longer matches the assignments file.

THE FAUCET
    TestTown's wallets are unfunded. To fund one, take its address to the
    official preprod faucet (a captcha page, so a human does it):
        https://faucet.preprod.midnight.network/
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSIGNMENTS = json.loads((ROOT / "tools" / "wallet-assignments.json").read_text())
OUT = ROOT / "docs" / "PREPROD_WALLETS.md"

FAUCET = "https://faucet.preprod.midnight.network/"

def named_operator_wallets():
    """The named operator wallets, in roster order (LADIES in the generator)."""
    text = (ROOT / "tools" / "generate_population.py").read_text()
    block = re.search(r"LADIES = \{(.*?)\}", text, re.S).group(1)
    return re.findall(r'"(\w+)":\s*"(mn_addr_preprod1\w+)"', block)

def short(address):
    """Middle-elide an address so the chart stays readable: first 24 … last 8."""
    return f"`{address[:24]}…{address[-8:]}`"

def build_chart():
    lines = []
    lines.append("# TestTown preprod wallets (public halves only)")
    lines.append("")
    lines.append("> GENERATED by `tools/generate_wallet_chart.py` from")
    lines.append("> `tools/wallet-assignments.json` and the operator wallets in")
    lines.append("> `tools/generate_population.py`. Do not edit by hand.")
    lines.append("")
    lines.append("Every address here is a **public** half. The seeds are in the")
    lines.append("local-only vault, never in this repo (`SECRETS_CONVENTION.md`).")
    lines.append("Every wallet is **unfunded** unless a balance check says otherwise.")
    lines.append("")
    lines.append("## The faucet")
    lines.append("")
    lines.append(f"| what | where |")
    lines.append(f"|---|---|")
    lines.append(f"| Official preprod tNIGHT faucet | {FAUCET} |")
    lines.append(f"| Nethermind mirror | https://midnight-tmnight-preprod.nethermind.dev/ |")
    lines.append("")
    lines.append("Both are the same captcha-protected page: paste an address, solve")
    lines.append("the captcha, and test tNIGHT arrives in a few minutes. The captcha")
    lines.append("means a human has to do this; it cannot be scripted.")
    lines.append("")

    ladies = named_operator_wallets()
    # Which institutions each named wallet operates, read from the dossiers.
    operates = {}
    for folder in sorted((ROOT / "dossiers" / "organizations").iterdir()):
        dossier = json.loads((folder / "dossier.json").read_text())
        card = (dossier.get("operator") or {}).get("walletCard") or ""
        match = re.search(r"wallet-([a-z]+)\.md$", card)
        if match:
            operates.setdefault(match.group(1), []).append(dossier["displayName"])

    lines.append(f"## Named operator wallets ({len(ladies)})")
    lines.append("")
    lines.append("Roster order. A wallet marked *spare* is not assigned to anything yet.")
    lines.append("")
    lines.append("| # | operator | operates | address |")
    lines.append("|---|---|---|---|")
    for number, (name, address) in enumerate(ladies, start=1):
        runs = "; ".join(operates.get(name, [])) or "*spare*"
        lines.append(f"| {number:02d} | {name} | {runs} | `{address}` |")
    lines.append("")

    wallets = ASSIGNMENTS["wallets"]
    citizens = sorted(s for s in wallets if not s.startswith(("VILLAIN", "quarry-street-exchange")))
    lines.append(f"## Assigned wallets ({len(wallets)} total)")
    lines.append("")
    lines.append("| who | address (elided) | full address |")
    lines.append("|---|---|---|")
    for slug in sorted(wallets):
        address = wallets[slug]["preprodAddress"]
        lines.append(f"| {slug} | {short(address)} | `{address}` |")
    lines.append("")
    lines.append("*Convention fixtures deliberately have no wallet: their own tests forbid a key.*")
    lines.append("")
    return "\n".join(lines)

def main():
    OUT.write_text(build_chart())
    print(f"wrote {OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
